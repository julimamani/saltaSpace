import fs from 'node:fs';
import path from 'node:path';

/**
 * Copies contract ABIs and every deployments/*.json to:
 *   front/src/app/web3/generated/{abis,deployments}.ts   (typed `as const` for viem)
 *   backend/app/chain/abi/*.json + backend/app/chain/deployments/*.json
 * Run after `hardhat compile` (done automatically by scripts/deploy.ts).
 */
const CONTRACTS = ['MockUSDC', 'LotToken', 'LotFactory', 'OracleConsumer', 'CampaignVault'];
const ROOT = path.join(__dirname, '..');
const REPO = path.join(ROOT, '..');

export function exportArtifacts() {
  const abis: Record<string, unknown> = {};
  for (const name of CONTRACTS) {
    const file = path.join(ROOT, 'artifacts', 'contracts', `${name}.sol`, `${name}.json`);
    abis[name] = JSON.parse(fs.readFileSync(file, 'utf8')).abi;
  }

  const depDir = path.join(ROOT, 'deployments');
  const deployments: Record<number, unknown> = {};
  const depFiles = fs.existsSync(depDir) ? fs.readdirSync(depDir).filter((f) => f.endsWith('.json')) : [];
  for (const f of depFiles) {
    const d = JSON.parse(fs.readFileSync(path.join(depDir, f), 'utf8'));
    deployments[d.chainId] = d;
  }

  const header = '// AUTO-GENERATED by contracts/scripts/export-abis.ts. Do not edit.\n';
  const frontDir = path.join(REPO, 'front', 'src', 'app', 'web3', 'generated');
  fs.mkdirSync(frontDir, { recursive: true });
  fs.writeFileSync(
    path.join(frontDir, 'abis.ts'),
    header +
      Object.entries(abis)
        .map(([name, abi]) => `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`)
        .join('\n'),
  );
  fs.writeFileSync(
    path.join(frontDir, 'deployments.ts'),
    header +
      `export interface Deployment {
  network: string;
  chainId: number;
  startBlock: number;
  deployer: string;
  oracle: string;
  contracts: { MockUSDC: \`0x\${string}\`; OracleConsumer: \`0x\${string}\`; LotFactory: \`0x\${string}\`; CampaignVault: \`0x\${string}\` };
  deployedAt: string;
}

export const DEPLOYMENTS: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
  );

  const backendAbi = path.join(REPO, 'backend', 'app', 'chain', 'abi');
  const backendDep = path.join(REPO, 'backend', 'app', 'chain', 'deployments');
  fs.mkdirSync(backendAbi, { recursive: true });
  fs.mkdirSync(backendDep, { recursive: true });
  for (const [name, abi] of Object.entries(abis)) {
    fs.writeFileSync(path.join(backendAbi, `${name}.json`), JSON.stringify(abi, null, 2) + '\n');
  }
  for (const f of depFiles) fs.copyFileSync(path.join(depDir, f), path.join(backendDep, f));

  console.log(`Exported ${CONTRACTS.length} ABIs and ${depFiles.length} deployment(s) to front/ and backend/`);
}

if (require.main === module) exportArtifacts();
